const assert = require('node:assert/strict');
const api = require('./stock-orders.js');
const item = (id, quantity, extra = {}) => ({id, name: 'صنف ' + id, code: id, packSize: 12, quantity, ...extra});
const data = {version: 3, items: [item('a', 24), item('b', 0), item('c', 25), item('d', 0, {reorderEnabled: false})], accounts: [], invoices: []};
const original = JSON.stringify(data);
const low = api.lowStock(data);
assert.deepEqual(low.map(row => [row.item.id, row.suggestedCartons]), [['a', 1], ['b', 3]]);
assert.deepEqual(api.lowStock({...data, items: [item('a', 1, {minStockCartons: 0})]}), []);
assert.equal(api.lowStock({...data, items: [item('a', 0, {minStockCartons: 0})]})[0].suggestedCartons, 1);
assert.throws(() => api.validate({...data, items: [item('a', 0, {minStockCartons: -1})]}));
assert.throws(() => api.create(data, {supplier: 'مورد', date: '2026-09-03', lines: []}, 'empty'));
assert.throws(() => api.create(data, {supplier: 'مورد', date: '2026-09-03', lines: [{itemId: 'd', cartons: 1}]}, 'excluded'));
const draft = {supplier: 'المورد', date: '2026-09-03', note: '', lines: [{itemId: 'a', cartons: 1}, {itemId: 'b', cartons: 2}]};
const ordered = api.create(data, draft, 'po-1');
assert.equal(JSON.stringify(data), original);
assert.equal(ordered.items[0].quantity, 24);
assert.equal(api.lowStock(ordered)[0].suggestedCartons, 0);
assert.equal(api.lowStock(ordered)[1].suggestedCartons, 1);
assert.throws(() => api.create(ordered, {...draft, lines: [{itemId: 'a', cartons: 1}]}, 'duplicate'));
assert.throws(() => api.create(data, {...draft, lines: [{itemId: 'a', cartons: 1.5}]}, 'fraction'));
assert.throws(() => api.create(data, {...draft, lines: [{itemId: 'a', cartons: Infinity}]}, 'infinity'));
const cancelled = api.cancel(ordered, 'po-1');
assert.equal(api.lowStock(cancelled)[0].suggestedCartons, 1);
assert.equal(cancelled.items[0].quantity, 24);
assert.throws(() => api.receive(cancelled, 'po-1', '2026-09-03', 'inv-1'));
assert.throws(() => api.receive(ordered, 'po-1', '2026-09-03', ''));
assert.throws(() => api.receive(ordered, 'po-1', '2026-09-02', 'inv-1'));
const repacked = {...ordered, items: ordered.items.map(i => i.id === 'a' ? {...i, packSize: 24} : i)};
const received = api.receive(repacked, 'po-1', '2026-09-04', 'inv-1');
assert.equal(received.items[0].quantity, 36); // Use the pack size agreed in the purchase order.
assert.equal(received.items[1].quantity, 24);
assert.equal(received.purchaseOrders[0].status, 'received');
assert.equal(ordered.purchaseOrders[0].status, 'pending');
assert.throws(() => api.receive(received, 'po-1', '2026-09-04', 'inv-1'));
assert.throws(() => api.cancel(received, 'po-1'));
assert.throws(() => api.validate({...ordered, items: ordered.items.filter(i => i.id !== 'a')}));
assert.deepEqual(api.validate(JSON.parse(JSON.stringify(received))), received);
const disabled = {...ordered, items: ordered.items.map(i => ({...i, reorderEnabled: false}))};
assert.deepEqual(api.lowStock(disabled), []);
assert.equal(api.receive(disabled, 'po-1', '2026-09-04', 'inv-2').items[0].quantity, 36);
console.log('Stock order tests passed: thresholds, rejection, suggestions, incoming orders, creation, cancellation, receipt, backup validation and no duplicate stock.');
